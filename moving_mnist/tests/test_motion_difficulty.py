def test_legacy_kernel_is_unchanged():
    """The default stream must reproduce every existing fixed benchmark."""
    import hashlib

    cases = {
        "piecewise_smooth08":  dict(motion_mode="piecewise", transition_mode="smooth",
                                    min_segment=3, max_segment=6, smooth_probability=0.8),
        "stochastic_smooth08": dict(motion_mode="stochastic", transition_mode="smooth",
                                    p_change=0.25, smooth_probability=0.8),
        "stochastic_smooth10": dict(motion_mode="stochastic", transition_mode="smooth",
                                    p_change=0.5, smooth_probability=1.0),
    }
    for name, kw in cases.items():
        ds = TDMovingMNISTDataset(
            root=DATA_ROOT, train=False, seq_len=SEQ_LEN, num_digits=NUM_DIGITS,
            image_size=36, max_speed=MAX_SPEED, freeze_after=FREEZE, download=False,
            random=False, seed=1234, return_motion=True, **kw)
        assert ds.neighbor_kernel == "legacy", "the default kernel must stay legacy"
        ds.reset_rng()
        h = hashlib.sha256()
        for _ in range(300):
            h.update(ds._generate_motion_trajectory().numpy().astype(np.int16).tobytes())
        assert h.hexdigest() == LEGACY_TRAJECTORY_SHA256[name], (
            f"{name}: the legacy trajectory stream changed")


def test_speed_is_not_confounded_with_difficulty():
    """The whole point of the symmetric kernel: mean |v| flat across the sweep."""
    rows = _all()
    for r in rows:
        assert math.isclose(r["mean_speed"], UNIFORM_MEAN_SPEED, rel_tol=0.01), (
            f"d={r['d']}: mean |v| {r['mean_speed']:.3f} drifted from the uniform-grid "
            f"value {UNIFORM_MEAN_SPEED}")


def test_jump_size_is_not_swept():
    """E|dv| is a separate axis and must be constant for every d that switches."""
    vals = [r["mean_dv"] for r in _all() if r["d"] > 0]
    assert max(vals) - min(vals) < 0.05 * np.mean(vals), f"E|dv| drifted: {vals}"


def test_anchor_points():
    zero = measure(0.0)
    assert zero["p_change"] == 0.0
    assert zero["entropy"] == 0.0
    assert zero["switches"] == 0.0

    train = measure(0.5)
    assert math.isclose(train["p_change"], 1 / 4.5, rel_tol=1e-3)
    assert math.isclose(train["p_smooth"], 0.80, rel_tol=1e-3)
    assert math.isclose(train["mean_gap"], 4.5, rel_tol=0.10)
    assert (train["min_segment"], train["max_segment"]) == (3, 6)

    top = measure(1.0)
    assert top["p_change"] == 1.0
    # deliberately NOT the maximum-entropy process: holding smooth_probability at
    # 0.80 trades peak entropy for coherent travel
    assert top["entropy"] < math.log2(23)


def test_monotonicity():
    rows = _all()
    for key in ("entropy", "switches"):
        vals = [r[key] for r in rows]
        assert all(a < b for a, b in zip(vals, vals[1:])), f"{key} not increasing: {vals}"
    for key in ("net_disp", "mean_age"):
        vals = [r[key] for r in rows]
        assert all(a > b for a, b in zip(vals, vals[1:])), f"{key} not decreasing: {vals}"


def test_regression_targets():
    for r in _all():
        exp = EXPECTED[round(r["d"], 2)]
        for name, e in zip(FIELDS, exp):
            g = r[name]
            if e == 0.0:
                assert abs(g) < 1e-9, f"d={r['d']} {name}: {g} != 0"
            else:
                assert math.isclose(g, e, rel_tol=0.05), f"d={r['d']} {name}: {g} vs {e}"


def test_max_speed_is_off_the_difficulty_axis():
    ref = _dataset(0.0)
    for d in D_GRID:
        ds = _dataset(d)
        assert ds.max_speed == ref.max_speed
        assert ds.velocity_grid == ref.velocity_grid


def test_apply_difficulty_does_not_consume_rng():
    ds = _dataset(0.0)
    ds.reset_rng()
    before = ds.rng.get_state()
    ds._apply_difficulty(0.73)
    after = ds.rng.get_state()
    assert before[0] == after[0]
    assert np.array_equal(before[1], after[1])
    assert before[2:] == after[2:]


def test_forced_mode_warns_only_on_conflict():
    import warnings

    def build(**kw):
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            TDMovingMNISTDataset(
                root=DATA_ROOT, train=False, seq_len=SEQ_LEN, num_digits=NUM_DIGITS,
                image_size=36, max_speed=MAX_SPEED, download=False, random=False,
                seed=SEED, **kw)
        return [w for w in caught if issubclass(w.category, UserWarning)]

    assert not build(motion_difficulty=0.5)
    assert not build(motion_mode="accelerate")
    for kw in (dict(motion_difficulty=0.5, motion_mode="accelerate"),
               dict(motion_difficulty=0.5, transition_mode="uniform")):
        got = build(**kw)
        assert got, f"expected a UserWarning for {kw}"
        assert "motion_mode" in str(got[0].message)

    ds = _dataset(0.5)
    assert ds.motion_mode == "stochastic"
    assert ds.transition_mode == "smooth"
    assert ds.smooth_probability == 0.80


